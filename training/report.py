"""Regenerate ``benchmarks/LEADERBOARD.md`` (+ plots) from ``runs/registry.sqlite``.

Rows: every ``train`` step with a ``done`` eval (FVC2004 DB1–4 B and FVC2004 full),
plus reference rows (classic RootSIFT, SourceAFIS) from ``benchmarks/results``.
Licence lineage ("open" vs "research-only") comes from the train records. Selection
metric shown is the val EER (manifest val ids); test numbers are reported only.

Usage::

    python -m training.report [--out benchmarks/LEADERBOARD.md]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from training.registry import Registry

__all__ = ["leaderboard_rows", "main", "reference_rows"]

REPO = Path(__file__).resolve().parents[1]


def reference_rows(results_dir: Path) -> list[dict]:
    """Mean FVC2004 DB1–4 B metrics of the committed comparator results."""

    rows = []
    for scorer, label in (("sourceafis", "SourceAFIS 3.14 (minutiae)"),
                          ("classic", "classic v2 (RootSIFT + RANSAC)")):
        sets = [results_dir / f"{scorer}_FVC2004_DB{i}_B.json" for i in range(1, 5)]
        if not all(p.is_file() for p in sets):
            continue
        ver = [json.loads(p.read_text(encoding="utf-8"))["verification"] for p in sets]
        per_db = [v["all"]["eer"] * 100 for v in ver]
        rows.append({"name": label, "track": "reference", "val": None,
                     "db_b_eer_all": float(np.mean(per_db)),
                     "db_b_eer_fvc": float(np.mean([v["fvc"]["eer"] * 100 for v in ver])),
                     "db_b_fmr100": float(np.mean([v["all"]["fmr100"] * 100 for v in ver])),
                     "db_b_fmr1000": float(np.mean([v["all"]["fmr1000"] * 100 for v in ver])),
                     "full_eer_all": None, "db_a_eer_all": None, "per_db": per_db})
    return rows


def leaderboard_rows(registry: Registry) -> list[dict]:
    trains = {r["key"]: r for r in registry.rows("train")}
    rows = []
    for ev in registry.rows("eval", "done"):
        train = trains.get(ev["parent_key"])
        if train is None:
            continue
        m = ev["metrics"] or {}
        results = json.loads(Path(ev["artifacts"]["results"]).read_text(encoding="utf-8"))
        per_db = [results["fvc2004_db_b"][f"FVC2004_DB{i}_B"]["eer_all"] for i in range(1, 5)]
        rows.append({
            "name": train["name"], "key": train["key"][:12],
            "track": (train.get("licence") or {}).get("track", "?"),
            "backbone": (train.get("config") or {}).get("model", {}).get("backbone", "?"),
            "val": (train.get("metrics") or {}).get("val_select"), **m, "per_db": per_db,
        })
    return sorted(rows, key=lambda r: r["db_b_eer_all"])


def _fmt(value: float | None, digits: int = 2) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def _plot(rows: list[dict], out: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if not rows:
        return
    fig, ax = plt.subplots(figsize=(10, 4.5))
    width = 0.8 / len(rows)
    for i, row in enumerate(rows):
        ax.bar(np.arange(4) + i * width, row["per_db"], width, label=row["name"])
    ax.set_xticks(np.arange(4) + 0.4 - width / 2, [f"DB{i}" for i in range(1, 5)])
    ax.set(ylabel="EER % (all impostors)", title="FVC2004 DB_B per-database EER")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(out / "fvc2004_db_b_eer.png", dpi=110)
    plt.close(fig)


def render(rows: list[dict], refs: list[dict]) -> str:
    lines = [
        "# Leaderboard — FVC2004 (held-out)",
        "",
        "_Generated by `python -m training.report` from `runs/registry.sqlite`; do not edit._",
        "Selection uses manifest val identities only; FVC2004 is never used for training,",
        "checkpoint or threshold selection. EER/FMR in %; DB_B = FVC2004 DB1–4 B "
        "(10 fingers, 2880 impostors/DB), full = 110 fingers/DB, DB_A = fingers 1–100.",
        "",
        "| model | track | backbone | val EER | DB_B EER all | DB_B EER fvc | DB_B FMR100 "
        "| DB_B FMR1000 | full EER all | DB_A EER all | DB_B per-DB EER |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in [*rows, *refs]:
        per_db = " / ".join(f"{v:.1f}" for v in r["per_db"])
        lines.append(
            f"| {r['name']} | {r['track']} | {r.get('backbone', '—')} | {_fmt(r['val'])} "
            f"| **{_fmt(r['db_b_eer_all'])}** | {_fmt(r['db_b_eer_fvc'])} "
            f"| {_fmt(r['db_b_fmr100'], 1)} | {_fmt(r['db_b_fmr1000'], 1)} "
            f"| {_fmt(r.get('full_eer_all'))} | {_fmt(r.get('db_a_eer_all'))} | {per_db} |")
    lines += ["", "![per-DB EER](leaderboard/fvc2004_db_b_eer.png)", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=REPO / "benchmarks" / "LEADERBOARD.md")
    args = parser.parse_args(argv)
    rows = leaderboard_rows(Registry())
    refs = reference_rows(REPO / "benchmarks" / "results")
    plots = args.out.parent / "leaderboard"
    plots.mkdir(parents=True, exist_ok=True)
    _plot([*rows, *refs], plots)
    args.out.write_text(render(rows, refs), encoding="utf-8")
    print(args.out)  # noqa: T201
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
